# Group by volume prefix
ECO_CODES_BY_PREFIX: dict[str, list[ECOEntry]] = {}
for entry in COMMON_ECO_CODES:
    ECO_CODES_BY_PREFIX.setdefault(entry.volume, []).append(entry)


class ECODatabase:
    """In-memory ECO code database with longest-prefix lookup."""

    def __init__(self, entries: list[ECOEntry] | None = None) -> None:
        self._entries = entries or COMMON_ECO_CODES
        self._index: dict[str, ECOEntry] = {e.code: e for e in self._entries}

    def lookup(self, code: str) -> ECOEntry | None:
        """Look up an ECO code exactly."""
        return self._index.get(code)

    def search_by_name(self, query: str) -> list[ECOEntry]:
        """Search openings by name (case-insensitive substring)."""
        q = query.lower()
        return [e for e in self._entries if q in e.name.lower()]

    def search_by_pgn(self, prefix: str) -> ECOEntry | None:
        """Find the longest matching PGN prefix."""
        matches = [e for e in self._entries if e.pgn and prefix.startswith(e.pgn)]
        if not matches:
            return None
        return max(matches, key=lambda e: len(e.pgn))

    def all_by_volume(self, volume: str) -> list[ECOEntry]:
        """Get all entries for a given volume (A/B/C/D/E)."""
        return ECO_CODES_BY_PREFIX.get(volume, [])

    @property
    def size(self) -> int:
        return len(self._entries)

    def all_codes(self) -> list[str]:
        return [e.code for e in self._entries]


def lookup_eco(code: str) -> ECOEntry | None:
    """Convenience: look up an ECO code."""
    return ECODatabase().lookup(code)


def is_eco_line(pgn: str, code: str) -> bool:
    """Check if a PGN prefix matches an ECO code's moves."""
    entry = lookup_eco(code)
    if not entry or not entry.pgn:
        return False
    return pgn.startswith(entry.pgn)
