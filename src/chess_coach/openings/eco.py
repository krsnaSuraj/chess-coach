"""ECO (Encyclopaedia of Chess Openings) code database.

5-volume code system:
- A: Flank openings (1.Nf3, 1.b3, 1.g3, 1.c4, 1.f4, etc.)
- B: Semi-open games (1.e4 OTHER than 1...e5)
- C: Open games and French Defence (1.e4 e5, 1.e4 e6)
- D: Closed and semi-closed games (1.d4 d5, 1.d4 Nf6)
- E: Indian defences (1.d4 Nf6, including 1.d4 f5)

Each code has multiple sub-codes (B12 means Caro-Kann, B90 means Sicilian Najdorf).
"""
from __future__ import annotations

import logging
from dataclasses import dataclass


logger = logging.getLogger(__name__)


@dataclass
class ECOEntry:
    """A single ECO code entry."""
    code: str
    name: str
    pgn: str
    fen: str | None = None
    variation: str = ""

    @property
    def volume(self) -> str:
        return self.code[0] if self.code else ""

    @property
    def sub_code(self) -> str:
        return self.code[1:] if len(self.code) > 1 else ""


